<script lang="ts">
  import { draftFromTxn } from '$lib/journal/writer';
  import { app } from '../state/app.svelte';
  import { editor } from '../state/editor.svelte';
  import { href } from '../state/router.svelte';
  import { todayISO } from '../lib/amounts';
  import Sheet from './Sheet.svelte';
  import Money from './Money.svelte';
  import Icon from './Icon.svelte';

  const t = $derived(editor.detail);
  const src = $derived(t ? app.sourceText(t) : null);
  let showSource = $state(false);

  function duplicate() {
    if (!t || !app.snapshot) return;
    const d = draftFromTxn(t, app.snapshot);
    editor.openNew({ ...d, date: todayISO(), status: '' });
  }
</script>

<Sheet bind:open={editor.detailOpen} title="Transaction" onclose={() => (showSource = false)}>
  {#if t}
    <div class="head">
      <div>
        <p class="date">{t.date}{t.date2 ? ` = ${t.date2}` : ''}</p>
        <h3>{t.description || '(no description)'}</h3>
        <p class="meta">
          {#if t.status === '*'}<span class="badge ok">Cleared</span>{:else if t.status === '!'}<span class="badge warn">Pending</span>{:else}<span class="badge">Unmarked</span>{/if}
          {#if t.code}<span class="badge">({t.code})</span>{/if}
          {#each t.tags as [k, v] (k + v)}<span class="badge"><Icon name="tag" size={12} /> {k}{v ? `: ${v}` : ''}</span>{/each}
        </p>
      </div>
    </div>
    <ul class="postings">
      {#each t.postings as p, i (i)}
        <li>
          <a href={href('account', p.account)} onclick={() => (editor.detailOpen = false)}>
            {p.type === 'virtual' ? `(${p.account})` : p.type === 'balanced-virtual' ? `[${p.account}]` : p.account}
          </a>
          <span class="amt"><Money value={p.amount} color />{#if p.inferred}<small class="muted"> inferred</small>{/if}</span>
          {#if p.amount.some((a) => a.cost)}<span class="sub muted">@ {p.amount.map((a) => a.cost ? `${a.cost.kind === 'total' ? '@' : ''}${a.cost.amount.quantity} ${a.cost.amount.commodity}` : '').join(' ')}</span>{/if}
          {#if p.assertion}<span class="sub muted">assert = {p.assertion.amount.quantity} {p.assertion.amount.commodity}</span>{/if}
          {#if p.comment.trim()}<span class="sub muted">; {p.comment.trim()}</span>{/if}
        </li>
      {/each}
    </ul>
    {#if t.comment.trim()}<p class="comment muted">; {t.comment.trim()}</p>{/if}
    {#if t.source}
      <p class="loc">
        <Icon name="file" size={14} />
        <a href="{href('files', t.source.file)}?line={t.source.startLine}" onclick={() => (editor.detailOpen = false)} class="mono">{t.source.file}:{t.source.startLine}</a>
        <button class="link" type="button" onclick={() => (showSource = !showSource)}>{showSource ? 'Hide' : 'Show'} source</button>
      </p>
      {#if showSource && src != null}<pre class="src">{src}</pre>{/if}
    {:else}
      <p class="muted">Generated by hledger (forecast or auto posting); not in any file.</p>
    {/if}
  {/if}
  {#snippet footer()}
    {#if t?.source}
      <button class="btn" type="button" onclick={duplicate} disabled={app.readOnly}><Icon name="copy" size={18} /> Duplicate</button>
      <button class="btn" type="button" onclick={() => t && editor.openEdit(t, true)} disabled={app.readOnly}><Icon name="code" size={18} /> Edit text</button>
      <button class="btn primary" type="button" onclick={() => t && editor.openEdit(t)} disabled={app.readOnly}><Icon name="edit" size={18} /> Edit</button>
    {/if}
  {/snippet}
</Sheet>

